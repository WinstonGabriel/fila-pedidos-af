BEGIN;
SELECT pg_advisory_xact_lock(802153,530);
DO $$
DECLARE codigo text; t1 text:=gen_random_uuid()::text; t2 text:=gen_random_uuid()::text; t3 text:=gen_random_uuid()::text;
  t4 text:=gen_random_uuid()::text; resposta json; id_atual text; id_seguinte text; outro text; bloqueou boolean; i integer;
  pool jsonb := '[{"id":"5300000000000001","cat":"Varejo","estab":"Loja A"},{"id":"5300000000000002","cat":"Varejo","estab":"Loja B"},{"id":"5300000000000003","cat":"Varejo","estab":"Loja preferida","preferencia":true}]';
BEGIN
  SELECT valor INTO codigo FROM public.fila_config WHERE chave='codigo';
  DELETE FROM public.fila_usuarios;
  DELETE FROM public.fila_atribuicoes;
  UPDATE public.fila_analistas SET ligado=false;
  INSERT INTO public.fila_usuarios(nome,token) VALUES('Gabriel',t1),('Rayla',t2),('Natalie',t3),('Cássio',t4);
  resposta:=public.fila_distribuir_auto(codigo,t1,NULL,pool);
  ASSERT (resposta->>'distribuidos')::int=0, 'OFF analyst triggered allocation';
  UPDATE public.fila_analistas SET ligado=true WHERE nome IN ('Gabriel','Rayla');
  resposta:=public.fila_distribuir_auto(codigo,t1,NULL,pool);
  ASSERT (resposta->>'distribuidos')::int=2, 'ON analysts did not receive work';
  ASSERT (SELECT count(*) FROM public.fila_atribuicoes WHERE status='em_andamento')=2, 'incorrect number of assignments';
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000003'), 'preferred order skipped';
  ASSERT NOT EXISTS(SELECT analista FROM public.fila_atribuicoes WHERE status='em_andamento' GROUP BY analista HAVING count(*)>1), 'two current orders per analyst';
  resposta:=public.fila_distribuir_auto(codigo,t2,NULL,pool);
  ASSERT (resposta->>'distribuidos')::int=0, 'repeated auto allocation was not idempotent';
  SELECT pedido_id INTO id_atual FROM public.fila_atribuicoes WHERE analista='Gabriel' AND status='em_andamento';
  resposta:=public.fila_avancar(codigo,t1,NULL,'Gabriel',id_atual,'concluir',pool);
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id=id_atual AND status='concluido'), 'completion did not finalize old order';
  SELECT pedido_id INTO id_seguinte FROM public.fila_atribuicoes WHERE analista='Gabriel' AND status='em_andamento';
  ASSERT id_seguinte IS NOT NULL AND id_seguinte<>id_atual, 'completion did not pull next order';
  resposta:=public.fila_avancar(codigo,t1,NULL,'Gabriel',id_atual,'concluir',pool);
  ASSERT (resposta->>'ja_processado')::boolean, 'duplicate completion was not detected';
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id=id_seguinte AND status='em_andamento'), 'duplicate completion consumed next order';
  resposta:=public.fila_avancar(codigo,t1,NULL,'Gabriel',id_seguinte,'liberar',pool);
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id=id_seguinte AND status='devolvido'), 'released order did not wait for another analyst';
  ASSERT NOT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE analista='Gabriel' AND status='em_andamento'), 'releaser immediately received own returned order';
  SELECT pedido_id INTO outro FROM public.fila_atribuicoes WHERE analista='Rayla' AND status='em_andamento';
  resposta:=public.fila_avancar(codigo,t2,NULL,'Rayla',outro,'concluir',pool);
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE analista='Rayla' AND pedido_id=id_seguinte AND status='em_andamento'), 'return was not reassigned to another available analyst';
  ASSERT EXISTS(SELECT 1 FROM public.fila_historico WHERE pedido_id=id_seguinte AND ator='Gabriel' AND acao='liberou_pedido'), 'release audit missing';

  UPDATE public.fila_analistas SET ligado=(nome IN ('Gabriel','Rayla','Natalie'));
  FOR i IN 1..10 LOOP
    DELETE FROM public.fila_atribuicoes;
    resposta:=public.fila_distribuir_auto(codigo,t2,NULL,'[{"id":"5300000000000009","cat":"Varejo"}]');
    ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000009' AND analista='Rayla' AND status='em_andamento'), 'analyst who switched ON lost the only order';
    DELETE FROM public.fila_atribuicoes;
    INSERT INTO public.fila_atribuicoes(pedido_id,analista,status,categoria) VALUES('5300000000000008','Gabriel','em_andamento','Varejo');
    resposta:=public.fila_avancar(codigo,t1,NULL,'Gabriel','5300000000000008','concluir','[{"id":"5300000000000009","cat":"Varejo"}]');
    ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000009' AND analista='Gabriel' AND status='em_andamento'), 'completion next order went to a different idle analyst';
  END LOOP;

  DELETE FROM public.fila_atribuicoes;
  UPDATE public.fila_analistas SET ligado=true WHERE nome='Natalie';
  INSERT INTO public.fila_atribuicoes(pedido_id,analista,status,categoria) VALUES('5300000000000004','Gabriel','em_andamento','Varejo');
  resposta:=public.fila_avancar(codigo,t1,NULL,'Gabriel','5300000000000004','liberar','[]');
  SELECT analista INTO outro FROM public.fila_atribuicoes WHERE pedido_id='5300000000000004';
  ASSERT outro IN ('Rayla','Natalie'), 'random recipient not in the other eligible ON analysts';

  DELETE FROM public.fila_atribuicoes;
  UPDATE public.fila_analistas SET ligado=false WHERE nome='Cássio';
  INSERT INTO public.fila_atribuicoes(pedido_id,analista,status,categoria) VALUES('5300000000000005','Gabriel','em_andamento','Força de Vendas');
  resposta:=public.fila_avancar(codigo,t1,NULL,'Gabriel','5300000000000005','liberar','[]');
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000005' AND status='devolvido'), 'FV sent to ineligible analysts';
  UPDATE public.fila_analistas SET ligado=true WHERE nome='Cássio';
  resposta:=public.fila_distribuir_auto(codigo,t1,NULL,'[]');
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000005' AND analista='Cássio' AND status='em_andamento'), 'FV did not reach the other eligible analyst';

  DELETE FROM public.fila_atribuicoes;
  UPDATE public.fila_analistas SET ligado=(nome='Gabriel');
  INSERT INTO public.fila_atribuicoes(pedido_id,analista,status,categoria) VALUES('5300000000000006','Gabriel','reservado','Varejo');
  resposta:=public.fila_distribuir_auto(codigo,t1,NULL,pool);
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000006' AND status='em_andamento'), 'manual reservation lost priority';
  resposta:=public.fila_avancar(codigo,t1,NULL,'Gabriel','5300000000000006','contato',pool);
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000006' AND status='contato'), 'contact flow regressed';
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE analista='Gabriel' AND status='em_andamento'), 'contact did not get the next order';

  DELETE FROM public.fila_atribuicoes;
  INSERT INTO public.fila_atribuicoes(pedido_id,analista,status,categoria) VALUES('5300000000000007','Gabriel','em_andamento','Varejo');
  PERFORM public.fila_liberar_pedido(codigo,t1,NULL,'Gabriel');
  ASSERT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE pedido_id='5300000000000007' AND status='devolvido'), 'legacy release still completes';
  resposta:=public.fila_puxar(codigo,t1,NULL,'Gabriel','[{"id":"5300000000000007","cat":"Varejo"}]');
  ASSERT resposta IS NULL, 'legacy client reclaimed its own returned order';
  UPDATE public.fila_analistas SET ligado=false WHERE nome='Gabriel';
  UPDATE public.fila_analistas SET ligado=true WHERE nome='Rayla';
  resposta:=public.fila_distribuir_auto(codigo,t2,NULL,pool);
  ASSERT NOT EXISTS(SELECT 1 FROM public.fila_atribuicoes WHERE analista='Gabriel' AND status='em_andamento'), 'OFF analyst received a new order';
  bloqueou:=false;
  BEGIN PERFORM public.fila_avancar(codigo,t1,NULL,'Rayla','5300000000000007','concluir',pool); EXCEPTION WHEN OTHERS THEN bloqueou:=true; END;
  ASSERT bloqueou, 'analyst acted on another analysts order';
  bloqueou:=false;
  BEGIN PERFORM public.fila_distribuir_auto(codigo,NULL,NULL,pool); EXCEPTION WHEN OTHERS THEN bloqueou:=true; END;
  ASSERT bloqueou, 'unidentified caller allocated orders';
  ASSERT NOT has_function_privilege('anon','public.fila_auto_alocar(text,boolean,jsonb,text)','execute'), 'internal allocator is public';
  PERFORM set_config('fila530.codigo',codigo,true);
  PERFORM set_config('fila530.token',t2,true);
END;
$$;
SET LOCAL ROLE anon;
SELECT public.fila_distribuir_auto(current_setting('fila530.codigo'),current_setting('fila530.token'),NULL,'[]')->>'ok' AS rpc_anon_authorized;
RESET ROLE;
ROLLBACK;
SELECT 'passed' AS automatic_distribution_database_checks, 'temporary fixtures rolled back; real work preserved' AS result;
